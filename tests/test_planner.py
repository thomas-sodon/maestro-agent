# --- symbol-stem / paired-test attribution bridges (issue #3769) ---


def test_symbol_named_file_verified_via_paired_test_and_symbol() -> None:
    """Regression for #3769: a fully-verified multi-file plan that refers to a
    touched code file by the class it defines (``Memory`` / ``Config``) and by
    its paired test file — never by the ``memory.py`` / ``config.py`` filename —
    must pass the scope gate.  Before the fix, attribution required a path or
    basename mention, so ``maestro/memory.py`` / ``maestro/config.py`` were
    reported as unverified and the whole plan was falsely rejected."""
    steps = [
        _step(
            "Add `Memory.count_actionable_plans()` to the memory layer. "
            "Verified by unit tests in tests/test_memory.py."
        ),
        _step(
            "Add a `Config` field for the new toggle. "
            "Verified by unit tests in tests/test_config.py."
        ),
        _step(
            "Wire the counter into maestro/agent.py and verify the "
            "integration end-to-end."
        ),
        _step("Update CLAUDE.md to document the new invariant."),
    ]
    files_affected = [
        "maestro/memory.py",
        "maestro/config.py",
        "maestro/agent.py",
        "tests/test_memory.py",
        "tests/test_config.py",
        "CLAUDE.md",
    ]
    ok, reason, _gaps = check_plan_scope_detailed(
        steps, files_affected=files_affected,
    )
    assert ok is True, reason


def test_symbol_bridge_does_not_rescue_genuinely_unverified_file() -> None:
    """Acceptance criterion 2 (#3769): the new bridges must NOT weaken the
    gate.  A code file whose stem-symbol and paired test appear in no
    verification-verb step still lands in the gap list and the plan is
    rejected, while the doc-only exemption is unchanged."""
    steps = [
        _step(
            "Add `Memory.count()` to the memory layer. "
            "Verified by unit tests in tests/test_memory.py."
        ),
        # Mentions maestro/silent.py and the `Silent` symbol, but with NO
        # verification verb — so neither the direct nor the symbol bridge
        # attributes verification to it.
        _step("Refactor maestro/silent.py internals and the Silent handler."),
        _step("Wire it into maestro/agent.py and verify the integration."),
        _step("Update CLAUDE.md to document it."),
    ]
    files_affected = [
        "maestro/memory.py",
        "maestro/silent.py",
        "maestro/agent.py",
        "tests/test_memory.py",
        "CLAUDE.md",
    ]
    ok, reason, gaps = check_plan_scope_detailed(
        steps, files_affected=files_affected,
    )
    assert ok is False
    assert "maestro/silent.py" in reason
    gap_paths = [p for p, _ in gaps]
    assert "maestro/silent.py" in gap_paths
    # The bridge-rescued file is not flagged; the doc file stays exempt.
    assert "maestro/memory.py" not in reason
    assert "CLAUDE.md" not in reason


def test_symbol_and_paired_test_bridge_helpers() -> None:
    """Guard branches of the two attribution bridges and their helpers."""
    # _paired_test_basename: normal, non-.py, already-a-test, empty stem.
    assert _paired_test_basename("maestro/memory.py") == "test_memory.py"
    assert _paired_test_basename("maestro/data.toml") is None
    assert _paired_test_basename("tests/test_memory.py") is None
    assert _paired_test_basename(".py") is None

    # _stem_pascalcase_symbol: single word, snake_case, too-short stem,
    # non-.py, test file, and an all-underscore stem yielding no parts.
    assert _stem_pascalcase_symbol("maestro/memory.py") == "Memory"
    assert _stem_pascalcase_symbol("maestro/task_queue.py") == "TaskQueue"
    assert _stem_pascalcase_symbol("maestro/db.py") is None
    assert _stem_pascalcase_symbol("maestro/data.toml") is None
    assert _stem_pascalcase_symbol("tests/test_memory.py") is None
    assert _stem_pascalcase_symbol("____.py") is None

    # Symbol-only rescue (no paired-test string in the verb step).
    assert (
        _symbol_or_test_verified(
            "maestro/config.py", [_step("Verify the Config flag behaviour")],
        )
        is True
    )
    # Paired-test-only rescue (symbol not named).
    assert (
        _symbol_or_test_verified(
            "maestro/memory.py", [_step("Tests added in tests/test_memory.py")],
        )
        is True
    )
    # Short-stem file: symbol is None, still rescued by the paired test.
    assert (
        _symbol_or_test_verified(
            "maestro/db.py", [_step("Verify tests/test_db.py")],
        )
        is True
    )
    # A test file is never symbol-bridged — both helpers yield no candidate.
    assert (
        _symbol_or_test_verified(
            "tests/test_memory.py",
            [_step("Verify Memory via tests/test_memory.py")],
        )
        is False
    )
    # Symbol named only in a non-verb step (skipped), and the verb step
    # misses — nothing rescues, so the file stays unverified.
    assert (
        _symbol_or_test_verified(
            "maestro/silent.py",
            [_step("Refactor the Silent handler"), _step("Verify unrelated plumbing")],
        )
        is False
    )


def test_file_referenced_in_handles_edge_cases() -> None:
    """Helper guards: empty file path returns False; trailing-slash path
    (empty basename) returns False; basenames match on whole-token boundary
    (so ``a.py`` does not falsely match ``data.py``)."""
    assert _file_referenced_in("Edit foo.py", "") is False
    # Trailing-slash path produces an empty basename — guard returns False.
    assert _file_referenced_in("Edit something", "dir/") is False
    # Bare canonical name not present in description: boundary-anchored
    # full-path regex misses, basename regex is identical and also misses.
    assert _file_referenced_in("Edit something.py", "missing.py") is False
    # Whole-token boundary: a canonical entry whose basename is ``a.py``
    # must NOT match the description ``Edit data.py`` (the substring fails
    # because the canonical entry includes a directory, and the basename
    # pass uses a leading-boundary anchor).
    assert _file_referenced_in("Edit data.py", "maestro/a.py") is False
    # Full path substring still wins:
    assert _file_referenced_in("Edit maestro/foo.py", "maestro/foo.py") is True
    # Basename match against a canonical full-path entry:
    assert _file_referenced_in("Verify foo.py works", "maestro/foo.py") is True


def test_file_referenced_in_rejects_substring_inside_longer_filename() -> None:
    """Bug: the full-path substring check (``file_path in description``) has
    no word-boundary awareness.  A bare canonical filename like ``foo.py``
    falsely matches inside a longer filename ``myfoo.py`` in the description
    because Python ``in`` is a raw substring test — the boundary-anchored
    basename regex never gets a chance to reject it.

    Similarly, ``README.md`` should NOT match inside ``MY_README.md``.
    """
    # Bare canonical name is a suffix of a longer filename in description.
    assert _file_referenced_in("Edit myfoo.py", "foo.py") is False
    # Bare canonical name embedded inside another filename with underscore.
    assert _file_referenced_in("Update MY_README.md", "README.md") is False
    # Sanity: the *actual* filename should still match.
    assert _file_referenced_in("Edit myfoo.py", "myfoo.py") is True
    assert _file_referenced_in("Update MY_README.md", "MY_README.md") is True
    # And a full-path entry whose basename is a suffix should also be
    # rejected — the substring check fires on the full path too when it
    # happens to appear inside the longer token.
    assert _file_referenced_in("Edit myfoo.py", "src/foo.py") is False
    assert _file_referenced_in("Update MY_README.md", "docs/README.md") is False


