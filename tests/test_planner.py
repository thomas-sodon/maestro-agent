def test_single_file_plan_with_eg_prose_should_not_be_rejected() -> None:
    """A single-file plan whose implementation step contains 'e.g.' in prose
    and whose verification language lives in a separate step must pass the
    scope gate.

    Regression for the file-path regex matching common non-path tokens like
    ``e.g``, ``i.e`` and ``Section 4.2`` — the spurious tokens used to be
    counted as additional files, kicking a real single-file plan into the
    multi-file branch and producing a bogus rejection.
    """
    steps = [
        PlanStep(
            step_id="pc_0",
            description=(
                "Update maestro/foo.py to handle edge cases (e.g. empty input)"
            ),
        ),
        PlanStep(
            step_id="pc_1",
            description=(
                "Add tests verifying maestro/foo.py covers Section 4.2 of the spec"
            ),
        ),
    ]
    ok, reason = check_plan_scope(steps)
    assert ok, f"expected pass for single-file plan, got rejection: {reason}"


def test_regex_does_not_match_common_non_path_tokens() -> None:
    """The file-path regex must not match common dotted prose tokens.

    ``EvolutionPlan.proposed_changes`` is free-form LLM prose; matching
    these tokens as files corrupts the multi-file branch decision.
    """
    for s in [
        "Use e.g. for examples",
        "See i.e. notes",
        "version 1.2 released",
        "visit github.com",
        "Section 4.2",
        "tag v1.4.0",
    ]:
        matches = [m.group(1) for m in _FILE_PATH_RE.finditer(s)]
        assert not matches, f"unexpected file matches in {s!r}: {matches}"


def test_regex_still_matches_real_paths_alongside_prose() -> None:
    """Real file references must still be detected when interleaved with
    prose tokens that previously tripped the regex."""
    s = (
        "Update maestro/foo.py (e.g. tighten validation) and `bar.py`; "
        "see Section 4.2 of v1.4 spec at github.com"
    )
    matches = [m.group(1) for m in _FILE_PATH_RE.finditer(s)]
    assert "maestro/foo.py" in matches
    assert "bar.py" in matches
    # And the prose tokens stay out:
    assert not any(m in {"e.g", "i.e", "1.2", "1.4", "v1.4", "4.2", "github.com"}
                   for m in matches)


