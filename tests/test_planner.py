def test_verification_re_matches_inflected_forms() -> None:
    """Inflected verb forms (plurals, -ing, -ies, -ed) are recognized.

    `proposed_changes` is free-form prose generated by the LLM, so natural
    inflections like 'Tests …', 'Verifies …', 'Validates …', 'Testing …'
    must match — otherwise valid multi-file plans get spuriously rejected
    by the scope gate.
    """
    inflected_phrases = [
        "Tests maestro/foo.py end-to-end",
        "Verifies maestro/bar.py output",
        "Validates resulting state",
        "Checks behavior matches expectation",
        "Asserts correctness of result",
        "Confirms file is updated",
        "Testing harness for module",
    ]
    for phrase in inflected_phrases:
        assert _VERIFICATION_RE.search(phrase), (
            f"Expected verification language to match in: {phrase!r}"
        )


def test_verification_re_matches_past_tense_forms() -> None:
    """Past-tense verb forms must be recognized for all verification verbs.

    Regression for asymmetric inflection coverage: the regex matched
    'verified' but not 'tested', 'asserted', 'checked', 'validated',
    or 'confirmed', causing spurious rejections of plans whose prose
    used past-tense verbs.
    """
    past_tense_phrases = [
        "Tested maestro/foo.py end-to-end",
        "Asserted correctness of result",
        "Checked maestro/bar.py behavior",
        "Validated resulting state",
        "Confirmed file is updated",
        "Verified maestro/baz.py output",
    ]
    for phrase in past_tense_phrases:
        assert _VERIFICATION_RE.search(phrase), (
            f"Expected past-tense verification language to match in: {phrase!r}"
        )


