# --- _find_unverified_code_files helper ---


def test_find_unverified_code_files_identifies_gaps() -> None:
    """Plan with 3 code files: 1 verified, 2 not → returns the 2
    unverified with correct (path, step_text) tuples."""
    steps = [
        PlanStep(step_id="pc_0", description="Edit maestro/foo.py to add helper"),
        PlanStep(step_id="pc_1", description="Wire maestro/bar.py to use helper"),
        PlanStep(step_id="pc_2", description="Tests verify maestro/baz.py end-to-end"),
        PlanStep(step_id="pc_3", description="Update maestro/baz.py docstrings"),
    ]
    gaps = _find_unverified_code_files(
        steps,
        files_affected=["maestro/foo.py", "maestro/bar.py", "maestro/baz.py"],
    )
    gap_paths = [p for p, _ in gaps]
    assert "maestro/foo.py" in gap_paths
    assert "maestro/bar.py" in gap_paths
    assert "maestro/baz.py" not in gap_paths
    assert len(gaps) == 2
    # Verify the step text is the first mentioning step for each file.
    gap_dict = dict(gaps)
    assert gap_dict["maestro/foo.py"] == "Edit maestro/foo.py to add helper"
    assert gap_dict["maestro/bar.py"] == "Wire maestro/bar.py to use helper"


